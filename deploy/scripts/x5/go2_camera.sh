#!/usr/bin/env bash
# go2_camera.sh - THE single entry point on the RDK X5 camera host.
# Everything the X5 does for the Go2 project lives here; systemd starts
# `go2_camera.sh run` at boot (unit: go2-camera.service, installed by
# scripts/x5/x5_install.sh from the laptop). The X5 never touches robot control.
#
#   go2_camera.sh run       service mode: wait for eth0 IP + D435i, generate the
#                           wired-only FastDDS profile, start realsense2_camera,
#                           restart it with backoff if it exits or the USB drops
#   go2_camera.sh once      one foreground run (debugging), Ctrl+C stops it
#   go2_camera.sh status    IP / link / USB speed / camera node & topics / log tail
#   go2_camera.sh env       print the ROS/DDS exports (eval "$(go2_camera.sh env)")
#   go2_camera.sh shell     bash with the ROS/DDS environment loaded
#   go2_camera.sh stop      stop the systemd service
#   go2_camera.sh clock     chrony state (tracking / sources) + the per-minute clock log
#
# Settings: /root/go2_camera_deploy/config/camera.conf (KEY=value, optional):
#   CAMERA_PROFILE=640x480x15   colour profile (WxHxFPS); also the depth one unless:
#   CAMERA_DEPTH_PROFILE=       depth profile when it differs (empty = CAMERA_PROFILE)
#   CAMERA_IMU=0|1              also publish gyro/accel (+ united /imu)
#   CAMERA_QOS=SENSOR_DATA      image/IMU publisher QoS (BEST_EFFORT+VOLATILE).
#                               SYSTEM_DEFAULT = RELIABLE, only for lossless recording tests
#   ROS_DOMAIN_ID=0             must equal the laptop's camera-consumer domain
#   LOG_KEEP=20                 how many camera logs to keep
#   CLOCK_WAIT_S=120            wait this long for chrony to sync from the laptop before the
#                               first camera start (0 = don't wait); frame stamps use this clock
#   CLOCK_MAX_OFFSET_S=0.010    "synced" = chrony tracking offset within this
#   CLOCK_STEP_RESTART=1        restart the camera node when the system clock steps by more than
#                               CLOCK_STEP_THRESHOLD_S (0 = only log the step, logs/clock.log)
#   CLOCK_STEP_THRESHOLD_S=0.05 step = wall-minus-monotonic time off by more than this on 2 polls
#                               in a row (2 s apart; a chrony slew never moves it). Below chrony's
#                               makestep 0.1 (chrony_x5.conf: every correction > 0.1 s is a step)
#                               and librealsense 2.58.4's 100 ms innovation gate (a bigger step
#                               leaves every D435i stamp off by the whole step for ~60 s), above
#                               the reader noise (~10 ms: /proc/uptime has 10 ms resolution).
#                               Write it as a positive decimal with '.'; anything else -> 0.05
set -uo pipefail

DEPLOY=/root/go2_camera_deploy
CONF="$DEPLOY/config"; LOGDIR="$DEPLOY/logs"; CAMERA_CONF="$CONF/camera.conf"
NIC=eth0
CAMERA_PROFILE=640x480x15
CAMERA_DEPTH_PROFILE=
CAMERA_IMU=0
CAMERA_QOS=SENSOR_DATA
ROS_DOMAIN_ID=0
LOG_KEEP=20
CLOCK_WAIT_S=120
CLOCK_MAX_OFFSET_S=0.010
CLOCK_STEP_RESTART=1
CLOCK_STEP_THRESHOLD_S=0.05
USB_ID="8086:0b3a"                       # Intel RealSense D435i
mkdir -p "$CONF" "$LOGDIR"
# shellcheck disable=SC1090
[ -f "$CAMERA_CONF" ] && source "$CAMERA_CONF"

log() { printf '[%s] %s\n' "$(date '+%F %T')" "$*"; }

# ---------------------------------------------------------------- environment
setup_env() {
  set +u                                         # TROS setup.bash reads unset variables (AMENT_TRACE_SETUP_FILES)
  if [ -f /opt/tros/humble/setup.bash ]; then
    # shellcheck disable=SC1091
    source /opt/tros/humble/setup.bash          # TROS Humble (RDK OS); layers on /opt/ros/humble
  elif [ -f /opt/ros/humble/setup.bash ]; then
    # shellcheck disable=SC1091
    source /opt/ros/humble/setup.bash
  else
    set -u; log "no ROS2 Humble found under /opt/tros or /opt/ros"; return 1
  fi
  set -u
  export ROS_DOMAIN_ID ROS_LOCALHOST_ONLY=0 RMW_IMPLEMENTATION=rmw_fastrtps_cpp
  unset CYCLONEDDS_URI
  export FASTRTPS_DEFAULT_PROFILES_FILE="$CONF/fastdds_x5_wired.xml"
  # systemd starts us without HOME; rcl's logging dir expands "~" and aborts the node otherwise
  export HOME="${HOME:-/root}" ROS_LOG_DIR="$LOGDIR/ros"; mkdir -p "$ROS_LOG_DIR"
}

eth0_ip() { ip -4 -o addr show "$NIC" 2>/dev/null | awk '{print $4}' | cut -d/ -f1 | head -1; }

# FastDDS participant bound to the X5's OWN wired address: no WiFi /
# usb0 address is ever announced, so the laptop only ever sees this NIC.
write_dds_profile() {
  local ip="$1"
  cat > "$CONF/fastdds_x5_wired.xml" <<XML
<?xml version="1.0" encoding="UTF-8" ?>
<!-- generated by go2_camera.sh for $NIC=$ip -->
<profiles xmlns="http://www.eprosima.com/XMLSchemas/fastRTPS_Profiles">
  <transport_descriptors>
    <transport_descriptor>
      <transport_id>udp_x5_wired</transport_id>
      <type>UDPv4</type>
      <interfaceWhiteList><address>$ip</address></interfaceWhiteList>
    </transport_descriptor>
  </transport_descriptors>
  <participant profile_name="x5_wired_participant" is_default_profile="true">
    <rtps>
      <userTransports><transport_id>udp_x5_wired</transport_id></userTransports>
      <useBuiltinTransports>false</useBuiltinTransports>
    </rtps>
  </participant>
</profiles>
XML
}

# ---------------------------------------------------------------- waits
wait_network() {                          # eth0 has an IPv4 address (ifupdown static)
  local n=0 ip
  while :; do
    ip="$(eth0_ip)"
    [ -n "$ip" ] && { echo "$ip"; return 0; }
    n=$((n + 1)); [ $((n % 15)) -eq 0 ] && log "waiting for $NIC IPv4 address (${n}s)"
    sleep 1
  done
}

camera_present() { lsusb 2>/dev/null | grep -q "$USB_ID"; }
camera_speed() {                          # 5000M (USB3) or 480M (USB2) or ""
  local dev
  dev="$(lsusb 2>/dev/null | awk -v id="$USB_ID" '$6==id {print $4}' | tr -d ':' | sed 's/^0*//')"
  [ -n "$dev" ] || return 0
  lsusb -t 2>/dev/null | awk -v d="Dev $dev," '$0 ~ d && /Class=Video/ {print $NF; exit}'
}
wait_camera() {
  local n=0
  until camera_present; do
    n=$((n + 1)); [ $((n % 15)) -eq 0 ] && log "waiting for D435i on USB ($((n * 2)) s)"
    sleep 2
  done
  local spd; spd="$(camera_speed)"
  if [ "$spd" = "5000M" ]; then log "D435i on USB 3.x (SuperSpeed)"
  else log "WARNING: D435i enumerated at ${spd:-unknown} - USB 2.0 path; use a USB 3.x A-to-C cable / port"; fi
}

# ---------------------------------------------------------------- clock
# The X5 RTC is dead (every boot starts in the year 2000). chrony (installed by
# scripts/x5/x5_chrony_setup.sh, config chrony_x5.conf) steps the clock from
# the laptop as soon as the laptop is reachable and then only slews. The
# camera's frame/IMU stamps follow this clock through librealsense's running
# device->host time fit, so (a) the node is started only after the first fix
# and (b) it is restarted whenever the clock steps again: a step under a
# running node leaves the stamps wrong for about a minute (driver log
# "clock fit re-based ... after 60 consecutive innovation-gate rejections").
have_chrony() { command -v chronyc >/dev/null 2>&1; }
clock_summary() {
  if have_chrony; then
    # -c fields: refid,refip,stratum,reftime,offset(+ = system clock SLOW of NTP time),lastoffset,rms,freq,resfreq,skew,rootdelay,rootdisp,updint,leap
    chronyc -c tracking 2>/dev/null | LC_ALL=C awk -F, '{printf "chrony stratum=%s offset=%+.6fs rms=%.6fs skew=%.3fppm leap=%s", $3, $5, $7, $10, $14}'
  else
    printf 'chrony not installed, system clock %s' "$(date '+%F %T')"
  fi
}
clock_synced() {                          # 0 = chrony has a fix within CLOCK_MAX_OFFSET_S
  have_chrony || return 1
  chronyc -c tracking 2>/dev/null | LC_ALL=C awk -F, -v max="$CLOCK_MAX_OFFSET_S" \
    '{ off = $5; if (off < 0) off = -off; ok = ($3 > 0 && $3 < 16 && $14 == "Normal" && off <= max) } END { exit !ok }'
}
check_clock() {                           # fallback without chrony: the laptop pushes time with x5_sync_time.sh
  if [ "$(date +%Y)" -lt 2024 ]; then
    log "WARNING: system clock is $(date '+%F') - not synced; run scripts/x5/x5_sync_time.sh from the laptop"
  fi
}
wait_time_sync() {                        # 0 synced, 1 gave up (camera starts anyway; clock_guard restarts it on the step)
  if ! have_chrony; then check_clock; return 1; fi
  local n=0
  while [ "$n" -lt "$CLOCK_WAIT_S" ]; do
    if clock_synced; then log "clock synced from the laptop: $(clock_summary); now $(date '+%F %T')"; return 0; fi
    n=$((n + 1)); [ $((n % 15)) -eq 0 ] && log "waiting for chrony to sync from the laptop (${n}s; $(clock_summary))"
    sleep 1
  done
  [ "$CLOCK_WAIT_S" -gt 0 ] && log "WARNING: clock not synced after ${CLOCK_WAIT_S}s ($(clock_summary)) - starting the camera anyway; it restarts when the clock steps"
  return 1
}
# Wall clock minus the uptime (boot-time) clock, in s with %.3f: a clock STEP
# moves it by the step, a chrony slew never moves it (both clocks are slewed
# together). The two clocks are read back to back with no fork in between
# ($EPOCHREALTIME needs bash >= 5, the X5 has 5.1; /proc/uptime goes through the
# `read` builtin). A locale with a decimal comma: bash writes EPOCHREALTIME with
# it (hence ${w/,/.}) and mawk would parse the split() fields with it, cutting
# both clocks to whole seconds (a false 1 s step), hence LC_ALL=C on every awk of
# the guard. A read preempted between the two clocks comes out LOW by the stall,
# so five pairs are taken and the MEDIAN returned: one or two stalled reads
# cannot fake a step, not even in the guard's base sample taken while ros2 launch starts.
wall_minus_mono() {
  local i w u _ s=""
  for i in 1 2 3 4 5; do
    w=${EPOCHREALTIME:-$(date +%s.%N)}; read -r u _ < /proc/uptime   # date only on bash < 5
    s+=" ${w/,/.} $u"
  done
  LC_ALL=C awk -v s="$s" 'BEGIN { n = split(s, a, " "); k = 0
    for (i = 1; i < n; i += 2) { d = a[i] - a[i + 1]; j = k; while (j > 0 && v[j] > d) { v[j + 1] = v[j]; j-- } v[j + 1] = d; k++ }
    printf "%.3f", v[int((k + 1) / 2)] }'
}
# Runs beside the camera launch (pid $1): kills it after a clock step (the
# service loop restarts it) and appends one tracking line per minute to
# logs/clock.log (the per-session record of the X5 clock).
# A step counts only when wall-minus-mono is off the base by more than
# CLOCK_STEP_THRESHOLD_S on 2 consecutive polls: a real step persists, a
# stalled poll does not. A threshold that is not a positive decimal (a camera.conf
# typo such as 0,05 or an empty value reads as 0 and would restart on the reader
# noise, in a loop) is replaced by 0.05 with a warning.
clock_guard() {
  local pid="$1" clog="$LOGDIR/clock.log" n=0 seen=0 thr="${CLOCK_STEP_THRESHOLD_S:-}" base cur diff
  if ! [[ "$thr" =~ ^[0-9]*\.?[0-9]+$ && "$thr" =~ [1-9] ]]; then
    log "WARNING: CLOCK_STEP_THRESHOLD_S='$thr' (camera.conf) is not a positive decimal like 0.05 - using 0.05"
    thr=0.05
  fi
  base="$(wall_minus_mono)"
  while kill -0 "$pid" 2>/dev/null; do
    sleep 2
    cur="$(wall_minus_mono)"
    diff="$(LC_ALL=C awk -v a="$cur" -v b="$base" 'BEGIN { d = a - b; if (d < 0) d = -d; printf "%.3f", d }')"
    if LC_ALL=C awk -v d="$diff" -v t="$thr" 'BEGIN { exit !(d + 0 > t + 0) }'; then
      seen=$((seen + 1))
    else
      seen=0
    fi
    if [ "$seen" -ge 2 ]; then
      log "clock stepped by ${diff}s (now $(date '+%F %T'); $(clock_summary))"
      printf '%s STEP %ss %s\n' "$(date '+%F %T')" "$diff" "$(clock_summary)" >> "$clog"
      if [ "$CLOCK_STEP_RESTART" = "1" ]; then
        log "restarting realsense2_camera so frame stamps follow the new clock"
        stop_pid_graceful "$pid"
        return 0
      fi
      base="$cur"; seen=0
    fi
    n=$((n + 1))
    if [ $((n % 30)) -eq 0 ]; then
      printf '%s %s\n' "$(date '+%F %T')" "$(clock_summary)" >> "$clog"
      if [ "$(stat -c %s "$clog" 2>/dev/null || echo 0)" -gt 2000000 ]; then
        tail -n 2000 "$clog" > "$clog.tmp" && cat "$clog.tmp" > "$clog" && rm -f "$clog.tmp"
      fi
    fi
  done
}

# Log rotation must not depend on the clock: the X5 RTC is dead, so right after
# boot new files are dated 2000 and would sort as the OLDEST. Each start gets a
# zero-padded sequence number from $LOGDIR/.camera_seq and rotation sorts by name.
next_seq() {
  local f="$LOGDIR/.camera_seq" n
  n="$(cat "$f" 2>/dev/null || echo 0)"; n=$((n + 1)); echo "$n" > "$f"; printf '%05d' "$n"
}
rotate_logs() {
  mkdir -p "$LOGDIR/old"
  mv "$LOGDIR"/camera_20[0-9][0-9]*.log "$LOGDIR/old/" 2>/dev/null || true     # date-named logs without a sequence number
  ls -1 "$LOGDIR"/camera_[0-9]*.log 2>/dev/null | sort | head -n -"$LOG_KEEP" | xargs -r rm -f
  # systemd appends service.log forever: keep the last 5000 lines once it passes 20 MB
  local svc="$LOGDIR/service.log"
  if [ -f "$svc" ] && [ "$(stat -c %s "$svc")" -gt 20000000 ]; then
    tail -n 5000 "$svc" > "$svc.tmp" && cat "$svc.tmp" > "$svc" && rm -f "$svc.tmp"
  fi
}

# ---------------------------------------------------------------- camera
# Node parameters that are NOT rs_launch.py arguments go through config_file
# (rs_launch.py reads it with yaml_to_dict: a FLAT key: value file, not the
# ros2 param dump format). Stream QoS lives here.
write_camera_params() {
  {
    echo "# generated by go2_camera.sh"
    echo "color_qos: $CAMERA_QOS"
    echo "depth_qos: $CAMERA_QOS"
    if [ "$CAMERA_IMU" = "1" ]; then echo "gyro_qos: $CAMERA_QOS"; echo "accel_qos: $CAMERA_QOS"; fi
  } > "$CONF/camera_params.yaml"
}

depth_profile() { echo "${CAMERA_DEPTH_PROFILE:-$CAMERA_PROFILE}"; }

launch_args() {
  local imu="enable_gyro:=false enable_accel:=false"
  [ "$CAMERA_IMU" = "1" ] && imu="enable_gyro:=true enable_accel:=true unite_imu_method:=2"
  write_camera_params
  # realsense-ros 4.58 argument names (rs_launch.py --show-args)
  echo camera_namespace:=camera camera_name:=d435i \
       enable_color:=true enable_depth:=true \
       rgb_camera.color_profile:="$CAMERA_PROFILE" depth_module.depth_profile:="$(depth_profile)" \
       enable_infra1:=false enable_infra2:=false \
       pointcloud.enable:=false align_depth.enable:=false \
       config_file:="$CONF/camera_params.yaml" \
       $imu
}

run_camera_once() {                       # foreground; returns when the launch exits
  local logfile="$LOGDIR/camera_$(next_seq)_$(date +%Y%m%d_%H%M%S).log"
  : > "$logfile"; ln -sfn "$logfile" "$LOGDIR/camera_latest.log"; rotate_logs
  log "starting realsense2_camera: profile=$CAMERA_PROFILE depth=$(depth_profile) imu=$CAMERA_IMU qos=$CAMERA_QOS domain=$ROS_DOMAIN_ID log=$logfile"
  # Background jobs of a non-interactive shell inherit SIGINT/SIGQUIT = ignored
  # and Python keeps that, so a plain `ros2 launch ... &` could never be stopped
  # with SIGINT (the launch would survive the guard's kill for minutes).
  # env --default-signal restores the default disposition, as the demo scripts do.
  # shellcheck disable=SC2046
  env --default-signal=INT,QUIT ros2 launch realsense2_camera rs_launch.py $(launch_args) "$@" > >(tee -a "$logfile") 2>&1 &
  LAUNCH_PID=$!
  clock_guard "$LAUNCH_PID" &
  local guard=$!
  wait "$LAUNCH_PID"; local rc=$?
  LAUNCH_PID=""
  kill "$guard" 2>/dev/null; wait "$guard" 2>/dev/null
  return "$rc"
}
LAUNCH_PID=""
# SIGINT lets ros2 launch close the streams cleanly (an abrupt kill has left the
# D435i with "Depth stream start failure" on the next start); escalate to TERM,
# then KILL of the launch and any orphaned camera node if it does not comply.
stop_pid_graceful() {
  local pid="$1" n
  kill -0 "$pid" 2>/dev/null || return 0
  kill -INT "$pid" 2>/dev/null
  for n in $(seq 1 15); do kill -0 "$pid" 2>/dev/null || return 0; sleep 1; done
  log "launch $pid ignored SIGINT for 15 s - sending SIGTERM"
  kill -TERM "$pid" 2>/dev/null
  for n in $(seq 1 10); do kill -0 "$pid" 2>/dev/null || return 0; sleep 1; done
  log "launch $pid ignored SIGTERM - SIGKILL (launch + camera node)"
  kill -KILL "$pid" 2>/dev/null; pkill -KILL -f realsense2_camera_node 2>/dev/null || true
}
stop_launch() {                           # forward the service stop to ros2 launch (clean stream close)
  log "stop requested"
  if [ -n "${LAUNCH_PID:-}" ]; then stop_pid_graceful "$LAUNCH_PID"; wait "$LAUNCH_PID" 2>/dev/null; fi
  exit 0
}

cmd_run() {                               # service loop
  local ip backoff=5
  trap stop_launch TERM INT
  ip="$(wait_network)"; log "$NIC=$ip"
  write_dds_profile "$ip"
  setup_env || exit 1
  wait_time_sync || true
  while :; do
    wait_camera
    run_camera_once; local rc=$?
    log "realsense2_camera exited rc=$rc - restarting in ${backoff}s"
    sleep "$backoff"; backoff=$(( backoff < 60 ? backoff * 2 : 60 ))
    camera_present && backoff=5           # camera still there: quick retry; else wait_camera blocks
  done
}

cmd_once() {
  local ip; ip="$(eth0_ip)"; [ -n "$ip" ] || { log "$NIC has no IPv4 address"; exit 1; }
  trap stop_launch TERM INT
  write_dds_profile "$ip"; setup_env || exit 1; wait_time_sync || true; wait_camera
  run_camera_once "$@"
}

cmd_status() {
  echo "== network =="; ip -br addr show "$NIC"; echo "link: $(cat /sys/class/net/$NIC/speed 2>/dev/null)Mb/s $(cat /sys/class/net/$NIC/duplex 2>/dev/null)"
  echo "== clock =="; date; clock_summary; echo; tail -n 3 "$LOGDIR/clock.log" 2>/dev/null
  echo "== usb =="; if camera_present; then echo "D435i present, speed $(camera_speed)"; else echo "D435i NOT enumerated"; fi
  echo "== service =="; systemctl is-active go2-camera.service 2>/dev/null; systemctl is-enabled go2-camera.service 2>/dev/null
  if setup_env 2>/dev/null; then
    echo "== ros graph (domain $ROS_DOMAIN_ID, whitelist $(eth0_ip)) =="
    timeout 8 ros2 node list 2>/dev/null; timeout 8 ros2 topic list 2>/dev/null | grep '^/camera' | head -20
  fi
  echo "== last log lines =="; tail -n 15 "$LOGDIR/camera_latest.log" 2>/dev/null
}

cmd_clock() {
  echo "== $(date '+%F %T') =="; clock_summary; echo
  if have_chrony; then echo "== chronyc sources =="; chronyc sources 2>/dev/null; echo "== chronyc tracking =="; chronyc tracking 2>/dev/null; fi
  echo "== logs/clock.log (last 10) =="; tail -n 10 "$LOGDIR/clock.log" 2>/dev/null
}

cmd_env() {
  local ip; ip="$(eth0_ip)"; [ -n "$ip" ] && write_dds_profile "$ip"
  local setup=/opt/tros/humble/setup.bash; [ -f "$setup" ] || setup=/opt/ros/humble/setup.bash
  echo "source $setup"
  echo "export ROS_DOMAIN_ID=$ROS_DOMAIN_ID ROS_LOCALHOST_ONLY=0 RMW_IMPLEMENTATION=rmw_fastrtps_cpp"
  echo "unset CYCLONEDDS_URI"
  echo "export FASTRTPS_DEFAULT_PROFILES_FILE=$CONF/fastdds_x5_wired.xml ROS_LOG_DIR=$LOGDIR/ros"
}

case "${1:-}" in
  run)    cmd_run ;;
  once)   shift; cmd_once "$@" ;;
  status) cmd_status ;;
  env)    cmd_env ;;
  shell)  eval "$(cmd_env)"; exec bash --norc -i ;;
  stop)   systemctl stop go2-camera.service ;;
  clock)  cmd_clock ;;
  *)      sed -n '2,36p' "$0"; exit 2 ;;
esac
